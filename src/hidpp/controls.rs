/// The name of control `cid`, in Italian when `italian` is true.
pub fn name(cid: u16, italian: bool) -> Option<&'static str> {
    NAMES
        .iter()
        .find(|(c, _, _)| *c == cid)
        .map(|(_, en, it)| if italian { *it } else { *en })
}

/// The name of control `cid`, or "Button 0x0123" when unknown.
pub fn name_or_number(cid: u16, italian: bool) -> String {
    match name(cid, italian) {
        Some(n) => n.to_owned(),
        None if italian => format!("Tasto {cid:#06x}"),
        None => format!("Button {cid:#06x}"),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_known_controls() {
        assert_eq!(name(0x0053, false), Some("Back"));
        assert_eq!(name(0x00E5, true), Some("Riproduci / Pausa"));
        assert_eq!(name_or_number(0x0FFF, false), "Button 0x0fff");
        assert_eq!(name_or_number(0x0FFF, true), "Tasto 0x0fff");
    }

    #[test]
    fn ids_are_unique() {
        for (i, a) in NAMES.iter().enumerate() {
            assert!(NAMES[i + 1..].iter().all(|b| b.0 != a.0), "{:#06x}", a.0);
        }
    }
}
